# Generates skeleton.rs (the bind skeleton incl. 30 finger bones, skin-bone capsules, the right hand's
# finger segments for the sculpt). Run:  python crates/privada-core/src/human/gen_skeleton.py
# Model space: metres, origin between the ears, y up, +z forward, L = -x. Bind pose: standing, arms hanging
# slightly out, palms toward the thighs, fingers relaxed (slightly curled).
import math, os

def n3(v):
    l = math.sqrt(sum(c * c for c in v)); return [c / l for c in v]
def add(a, b): return [a[i] + b[i] for i in range(3)]
def mul(a, s): return [c * s for c in a]

NECK = [0.0, -0.148, -0.034]; HEAD = [0.0, -0.072, -0.022]; HINGE = [0.0, -0.020, -0.008]; EYE = [0.0318, 0.0100, 0.0668]
# (name, parent name, bind position, segment end (for skinning), owned radius; None = not a skin bone)
B = [
    ('root', None, [0, 0, 0], None, None),
    ('pelvis', 'root', [0, -0.720, -0.030], [0, -0.800, -0.030], 0.120),
    ('spine1', 'pelvis', [0, -0.620, -0.030], [0, -0.540, -0.030], 0.120),
    ('spine2', 'spine1', [0, -0.500, -0.030], [0, -0.410, -0.030], 0.120),
    ('chest', 'spine2', [0, -0.370, -0.030], [0, -0.240, -0.035], 0.125),
    ('neck', 'chest', NECK, [0, -0.100, -0.026], 0.052),
    ('head', 'neck', HEAD, [0, 0.040, -0.010], 0.090),
    ('jaw', 'head', HINGE, None, None),
    ('eye_L', 'head', [-EYE[0], EYE[1], EYE[2]], None, None),
    ('eye_R', 'head', EYE, None, None),
]
def side(sx, S):
    x = lambda v: [v[0] * sx, v[1], v[2]]
    B.extend([
        ('clavicle_' + S, 'chest', x([0.025, -0.235, -0.030]), x([0.170, -0.262, -0.036]), 0.050),
        ('upperarm_' + S, 'clavicle_' + S, x([0.190, -0.272, -0.038]), x([0.236, -0.558, -0.035]), 0.052),
        ('forearm_' + S, 'upperarm_' + S, x([0.236, -0.558, -0.035]), x([0.258, -0.800, -0.012]), 0.043),
        ('hand_' + S, 'forearm_' + S, x([0.258, -0.800, -0.012]), x([0.263, -0.900, 0.000]), 0.030),
    ])
side(-1, 'L'); side(1, 'R')
def leg(sx, S):
    x = lambda v: [v[0] * sx, v[1], v[2]]
    B.extend([
        ('thigh_' + S, 'pelvis', x([0.092, -0.790, -0.030]), x([0.100, -1.170, -0.022]), 0.085),
        ('shin_' + S, 'thigh_' + S, x([0.100, -1.170, -0.022]), x([0.100, -1.555, -0.035]), 0.058),
        ('foot_' + S, 'shin_' + S, x([0.100, -1.555, -0.035]), x([0.100, -1.600, 0.120]), 0.050),
    ])
leg(-1, 'L'); leg(1, 'R')

# right hand fingers: (name, base, lengths, radius, splay z per unit length); they hang -y, curling toward -x
CURL = 0.17
FING = [
    ('index', [0.2640, -0.9050, 0.0290], [0.040, 0.024, 0.021], 0.0093, 0.06),
    ('middle', [0.2650, -0.9100, 0.0095], [0.044, 0.028, 0.022], 0.0096, 0.00),
    ('ring', [0.2640, -0.9050, -0.0095], [0.040, 0.026, 0.021], 0.0090, -0.05),
    ('pinky', [0.2620, -0.8930, -0.0275], [0.031, 0.019, 0.019], 0.0080, -0.12),
]
hand_segs = []   # (a, b, ra, rb) right hand
finger_bones = []  # (name, parent, pos, end, r) right hand
t0 = [0.2580, -0.8320, 0.0300]
tdirs = [n3([-0.25, -0.62, 0.74]), n3([-0.20, -0.80, 0.55]), n3([-0.22, -0.90, 0.38])]
tlens = [0.038, 0.032, 0.027]; trad = [0.0135, 0.0108, 0.0098, 0.0088]
p = t0
for k in range(3):
    e = add(p, mul(tdirs[k], tlens[k]))
    finger_bones.append(('thumb%d' % (k + 1), 'hand' if k == 0 else 'thumb%d' % k, p, e, trad[k]))
    hand_segs.append((p, e, trad[k], trad[k + 1]))
    p = e
for name, base, lens, r, splay in FING:
    p = base
    for k in range(3):
        a = CURL * (k + 1)
        d = n3([-math.sin(a), -math.cos(a), splay])
        e = add(p, mul(d, lens[k]))
        finger_bones.append(('%s%d' % (name, k + 1), 'hand' if k == 0 else '%s%d' % (name, k), p, e, r * 0.92 ** k))
        hand_segs.append((p, e, r * 0.92 ** k, r * 0.92 ** (k + 1)))
        p = e
for sx, S in ((-1, 'L'), (1, 'R')):
    for name, par, pos, end, r in finger_bones:
        B.append(('%s_%s' % (name, S), '%s_%s' % (par, S), [pos[0] * sx, pos[1], pos[2]], [end[0] * sx, end[1], end[2]], r))
B.append(('plug', 'root', [0, 0, 0], None, None))

idx = {b[0]: i for i, b in enumerate(B)}
f = lambda v: '[' + ', '.join('%.5f' % c for c in v) + ']'
out = ['//! GENERATED by gen_skeleton.py - do not edit by hand.',
       '//! Bind skeleton (parents first; `plug` lives in root space), skin bones with the capsule each one owns,',
       '//! and the right hand\'s finger segments used by the sculpt (mirror x for the left hand).',
       '', '/// (name, parent index or -1, bind position in model space)',
       'pub const SKELETON: [(&str, i32, [f32; 3]); %d] = [' % len(B)]
for name, par, pos, end, r in B:
    out.append('    ("%s", %d, %s),' % (name, -1 if par is None else idx[par], f(pos)))
out.append('];')
out.append('pub mod node {')
for name, i in idx.items():
    out.append('    pub const %s: usize = %d;' % (name.upper(), i))
out.append('}')
skin = [b for b in B if b[4] is not None]
out.append('/// bones that deform meshes, in skin-index order (indices into [`SKELETON`])')
out.append('pub const SKIN_BONES: [usize; %d] = [%s];' % (len(skin), ', '.join(str(idx[b[0]]) for b in skin)))
out.append('/// the capsule each skin bone owns: (from, to, radius), same order as [`SKIN_BONES`]')
out.append('pub const SKIN_SEGS: [([f32; 3], [f32; 3], f32); %d] = [' % len(skin))
for b in skin:
    out.append('    (%s, %s, %.4f), // %s' % (f(b[2]), f(b[3]), b[4], b[0]))
out.append('];')
out.append('/// right-hand finger segments (from, to, radius at from, radius at to): thumb x3, index x3, middle x3, ring x3, pinky x3')
out.append('pub const HAND_SEGS: [([f32; 3], [f32; 3], f32, f32); %d] = [' % len(hand_segs))
for a, b, ra, rb in hand_segs:
    out.append('    (%s, %s, %.5f, %.5f),' % (f(a), f(b), ra, rb))
out.append('];')
si = {b[0]: i for i, b in enumerate(skin)}
out.append('/// skin indices of chest / neck / head (what `head::skin_weights` refers to)')
out.append('pub const SKIN_CHEST_NECK_HEAD: [u8; 3] = [%d, %d, %d];' % (si['chest'], si['neck'], si['head']))
out.append('/// first finger node of each hand (thumb1), 15 consecutive nodes: thumb, index, middle, ring, pinky x 3 joints')
out.append('pub const FINGERS_L: usize = %d;' % idx['thumb1_L'])
out.append('pub const FINGERS_R: usize = %d;' % idx['thumb1_R'])
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'skeleton.rs'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('skeleton.rs:', len(B), 'nodes,', len(skin), 'skin bones')
